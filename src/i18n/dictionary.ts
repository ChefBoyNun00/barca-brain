export const DICTIONARY: Record<Language, Record<TextKey, string>> = { en, he };

const ORDINALS: Record<Language, (n: number) => string> = {
  en: (n) => {
    const lastTwo = n % 100;
    if (lastTwo >= 11 && lastTwo <= 13) return `${n}th`;
    return `${n}${({ 1: "st", 2: "nd", 3: "rd" } as Record<number, string>)[n % 10] ?? "th"}`;
  },
  // Hebrew writes "place 2" (מקום 2), so the number needs no ending.
  he: (n) => String(n),
};

/** 2 becomes 2nd in English and stays 2 in Hebrew. */
export const ordinal = (language: Language, n: number): string => ORDINALS[language](n);

export type TextVars = Record<string, string | number>;

/**
 * In a right-to-left sentence, a filled-in name or score is wrapped in Unicode isolate marks
 * (invisible), so "Real Madrid" or "2–1" keeps its own direction and never flips the words
 * around it. A score like 2–1 would otherwise show as 1–2.
 */
const isolate = (text: string) => `\u2068${text}\u2069`;

/** Looks a key up in the chosen language and fills in its {placeholders}. */
export function translate(language: Language, key: TextKey, vars: TextVars = {}): string {
  const rtl = RTL_LANGUAGES.includes(language);
  return DICTIONARY[language][key].replace(/\{(\w+)(?::(ordinal))?\}/g, (whole, name, format) => {
    const value = vars[name];
    if (value === undefined) return whole;
    if (format === "ordinal") return ORDINALS[language](Number(value));
    return rtl && typeof value === "string" ? isolate(value) : String(value);
  });
}

/** A translate function already set to one language: what useT() returns. */
export type Translate = (key: TextKey, vars?: TextVars) => string;

export const translatorFor =
  (language: Language): Translate =>
  (key, vars) =>
    translate(language, key, vars);

/** For text that arrives from elsewhere, such as a tool name from the server. */
export const isTextKey = (key: string): key is TextKey => Object.hasOwn(DICTIONARY.en, key);

export const isLanguage = (value: unknown): value is Language =>
  LANGUAGES.some((language) => language === value);
